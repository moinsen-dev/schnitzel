import tempfile
import os
from pathlib import Path
from typer.testing import CliRunner
import pytest

from schnitzel.cli import app

runner = CliRunner()


@pytest.fixture
def temp_dir():
    """Create a temporary directory for testing and change to it."""
    original_cwd = os.getcwd()
    with tempfile.TemporaryDirectory() as tmpdir:
        os.chdir(tmpdir)
        yield Path(tmpdir)
        os.chdir(original_cwd)


@pytest.fixture
def schema_file(temp_dir: Path) -> Path:
    """Create a test schema file."""
    schema_content = """schnitzel: 1.0.0

models:
  User:
    description: A user in the system
    fields:
      id:
        type: uuid
        primary: true
      name:
        type: string
      email:
        type: string
        unique: true
      created_at:
        type: datetime
        auto: create

  Post:
    description: A blog post
    fields:
      id:
        type: uuid
        primary: true
      title:
        type: string
      content:
        type: string
      author_id:
        type: uuid
      created_at:
        type: datetime
        auto: create
    relations:
      author:
        type: belongsTo
        model: User
        foreign_key: author_id
"""
    schema_file = temp_dir / "schema.schnitzel.yaml"
    schema_file.write_text(schema_content)
    return schema_file


def test_generate_all_creates_python_models(temp_dir: Path, schema_file: Path) -> None:
    """Test that generate --target all creates Python Pydantic models."""
    # Run generate command with --target all
    result = runner.invoke(app, ["generate", str(schema_file), "--target", "all", "--output", str(temp_dir)])

    # Verify command succeeded
    assert result.exit_code == 0, f"Command failed: {result.stdout}"

    # Verify Python models were created
    python_models_file = temp_dir / "backend" / "app" / "models.py"
    assert python_models_file.exists(), "Python models.py not created"
    assert python_models_file.is_file(), "Python models.py is not a file"

    # Verify content
    content = python_models_file.read_text()
    assert "class User(BaseModel):" in content, "Missing User model"
    assert "class Post(BaseModel):" in content, "Missing Post model"
    assert "from pydantic import BaseModel" in content, "Missing pydantic import"
    assert "Generated by Schnitzel Framework" in content, "Missing header comment"


