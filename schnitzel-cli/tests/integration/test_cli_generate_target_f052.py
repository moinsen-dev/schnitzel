def test_generate_force_flag_overwrites_files(temp_dir: Path, schema_file: Path) -> None:
    """Test that --force flag allows overwriting existing files."""
    # Run generate command first time
    result1 = runner.invoke(app, ["generate", str(schema_file), "-t", "python", "-o", str(temp_dir)])
    assert result1.exit_code == 0, f"First command failed: {result1.stdout}"

    # Verify file was created
    python_models_file = temp_dir / "backend" / "app" / "models.py"
    assert python_models_file.exists(), "Python models.py not created"

    # Get original content
    original_content = python_models_file.read_text()

    # Run generate command again without --force (should skip)
    result2 = runner.invoke(app, ["generate", str(schema_file), "-t", "python", "-o", str(temp_dir)])
    assert result2.exit_code == 0, f"Second command failed: {result2.stdout}"

    # Content should be the same (file was not overwritten)
    content_after_no_force = python_models_file.read_text()
    assert content_after_no_force == original_content, "File should not be overwritten without --force"

    # Run generate command again with --force
    result3 = runner.invoke(app, ["generate", str(schema_file), "-t", "python", "-o", str(temp_dir), "--force"])
    assert result3.exit_code == 0, f"Third command failed: {result3.stdout}"

    # Content should be different (file was overwritten with new timestamp)
    content_after_force = python_models_file.read_text()
    # Both should have content but timestamps will be different
    assert "Generated by Schnitzel Framework" in content_after_force, "File should be regenerated"


